using Microsoft.EntityFrameworkCore;

namespace Milvasoft.BulkExtensions.Tests.Infrastructure;

public enum ProductStatus
{
    Draft,
    Active,
    Discontinued,
}

/// <summary>
/// Mapped to a native PostgreSQL enum.
/// </summary>
public enum Mood
{
    Happy,
    Sad,
}

public class Category
{
    public Guid Id { get; set; }

    public string Name { get; set; }

    public List<Product> Products { get; set; } = [];
}

public class Product
{
    public int Id { get; set; }

    public string Sku { get; set; }

    public string Name { get; set; }

    public string Description { get; set; }

    public decimal Price { get; set; }

    public ProductStatus Status { get; set; }

    public List<string> Tags { get; set; } = [];

    public DateOnly? ReleaseDate { get; set; }

    /// <summary>
    /// Database default <c>now()</c>.
    /// </summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>
    /// Stored computed column.
    /// </summary>
    public int NameLength { get; set; }

    /// <summary>
    /// PostgreSQL <c>xmin</c> row version.
    /// </summary>
    public uint Version { get; set; }

    public Mood? Mood { get; set; }

    public Dimensions Size { get; set; } = new();

    public Guid? CategoryId { get; set; }

    public Category Category { get; set; }
}

/// <summary>
/// Complex type.
/// </summary>
public class Dimensions
{
    public double Width { get; set; }

    public double Height { get; set; }
}

public abstract class Animal
{
    public long Id { get; set; }

    public string Name { get; set; }
}

public class Dog : Animal
{
    public string Breed { get; set; }

    /// <summary>
    /// Owned type of a derived TPH type.
    /// </summary>
    public Collar Collar { get; set; }
}

public class Collar
{
    public string Color { get; set; }

    public int Size { get; set; }
}

public class Cat : Animal
{
    public int Lives { get; set; }
}

public class Order
{
    public int Id { get; set; }

    public string Number { get; set; }

    /// <summary>
    /// Owned type stored in the Orders table.
    /// </summary>
    public Address ShippingAddress { get; set; }

    /// <summary>
    /// Owned collection stored in its own table.
    /// </summary>
    public List<OrderLine> Lines { get; set; } = [];
}

public class Address
{
    public string Street { get; set; }

    public string City { get; set; }
}

public class OrderLine
{
    public string Product { get; set; }

    public int Quantity { get; set; }
}

/// <summary>
/// Has a shadow foreign key <c>ProductId</c>.
/// </summary>
public class Review
{
    public int Id { get; set; }

    public string Text { get; set; }

    public Product Product { get; set; }
}

/// <summary>
/// Composite primary key.
/// </summary>
public class Inventory
{
    public int WarehouseId { get; set; }

    public string ProductCode { get; set; }

    public int Quantity { get; set; }
}

public class TreeNode
{
    public int Id { get; set; }

    public string Name { get; set; }

    public int? ParentId { get; set; }

    public TreeNode Parent { get; set; }

    public List<TreeNode> Children { get; set; } = [];
}

/// <summary>
/// Every column is generated by the database.
/// </summary>
public class Ticket
{
    public int Id { get; set; }

    public DateTime IssuedAt { get; set; }
}

/// <summary>
/// Blank padded <c>character(3)</c> primary key.
/// </summary>
public class Currency
{
    public string Code { get; set; }

    public string Name { get; set; }

    public uint Version { get; set; }
}

/// <summary>
/// TPC hierarchy: no table for the base type.
/// </summary>
public abstract class Vehicle
{
    public int Id { get; set; }

    public string Plate { get; set; }
}

public class Car : Vehicle
{
    public int Seats { get; set; }
}

public class Truck : Vehicle
{
    public int Axles { get; set; }
}

/// <summary>
/// Refers to the TPC base type.
/// </summary>
public class Trip
{
    public int Id { get; set; }

    public int VehicleId { get; set; }

    public Vehicle Vehicle { get; set; }
}

public partial class TestDbContext(DbContextOptions options) : DbContext(options)
{
    public DbSet<Category> Categories => Set<Category>();

    public DbSet<Product> Products => Set<Product>();

    public DbSet<Animal> Animals => Set<Animal>();

    public DbSet<Order> Orders => Set<Order>();

    public DbSet<Review> Reviews => Set<Review>();

    public DbSet<Inventory> Inventories => Set<Inventory>();

    public DbSet<TreeNode> TreeNodes => Set<TreeNode>();

    public DbSet<Ticket> Tickets => Set<Ticket>();

    public DbSet<Currency> Currencies => Set<Currency>();

    public DbSet<Vehicle> Vehicles => Set<Vehicle>();

    public DbSet<Trip> Trips => Set<Trip>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Product>(b =>
        {
            b.HasIndex(p => p.Sku).IsUnique();
            b.Property(p => p.Sku).HasMaxLength(50).IsRequired();
            b.Property(p => p.Name).HasMaxLength(100).IsRequired();
            b.Property(p => p.Price).HasPrecision(18, 2);
            b.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);
            b.Property(p => p.CreatedAt).HasDefaultValueSql("now()");
            b.Property(p => p.NameLength).HasComputedColumnSql("length(\"Name\")", stored: true);
            b.Property(p => p.Version).IsRowVersion();
            b.ComplexProperty(p => p.Size);
            b.HasOne(p => p.Category).WithMany(c => c.Products).HasForeignKey(p => p.CategoryId);
        });

        modelBuilder.Entity<Animal>(b =>
        {
            b.HasDiscriminator<string>("Kind").HasValue<Dog>("dog").HasValue<Cat>("cat");
        });

        modelBuilder.Entity<Dog>();
        modelBuilder.Entity<Cat>();

        modelBuilder.Entity<Order>(b =>
        {
            b.OwnsOne(o => o.ShippingAddress);
            b.OwnsMany(o => o.Lines, l => l.ToTable("OrderLines"));
        });

        modelBuilder.Entity<Review>().HasOne(r => r.Product).WithMany().HasForeignKey("ProductId").IsRequired();

        modelBuilder.Entity<Inventory>().HasKey(i => new { i.WarehouseId, i.ProductCode });

        modelBuilder.Entity<TreeNode>().HasOne(n => n.Parent).WithMany(n => n.Children).HasForeignKey(n => n.ParentId);

        modelBuilder.Entity<Ticket>().Property(t => t.IssuedAt).HasDefaultValueSql("now()");

        modelBuilder.Entity<Category>().HasIndex(c => c.Name).IsUnique();

        modelBuilder.Entity<Currency>(b =>
        {
            b.HasKey(c => c.Code);
            b.Property(c => c.Code).HasColumnType("character(3)");
            b.Property(c => c.Version).IsRowVersion();
        });

        modelBuilder.Entity<Vehicle>().UseTpcMappingStrategy();
        modelBuilder.Entity<Car>().ToTable("Cars");
        modelBuilder.Entity<Truck>().ToTable("Trucks");

        ConfigureExtendedModel(modelBuilder);
    }
}