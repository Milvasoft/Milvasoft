using Microsoft.IdentityModel.Tokens;
using System.Security.Cryptography;

namespace Milvasoft.Identity.TokenProvider.AuthToken;

#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member
public class TokenConfig
{
    private const string _digitTokenSecretDerivationLabel = "Milvasoft.Identity.DigitTokenSecret";

    public bool UseUtcForDateTimes { get; set; }
    public int ExpirationMinute { get; set; }
    public SecurityKeyType SecurityKeyType { get; set; }
    public TokenValidationParameters TokenValidationParameters { get; set; }
    public string SymmetricPublicKey { get; set; }
    public RsaPublicKey RsaPublicKey { get; set; }

    /// <summary>
    /// Server-side secret (at least 32 bytes in UTF-8) used to derive the keys of the 6 digit codes generated by
    /// <see cref="DigitTokenProvider{TUser, TKey}"/> through the user manager. Never send it to clients.
    /// If it is not set and <see cref="SecurityKeyType"/> is <see cref="SecurityKeyType.Symmetric"/>, a secret is derived
    /// from <see cref="SymmetricPublicKey"/> (domain separated with HMAC-SHA256, so codes never reveal the JWT key).
    /// </summary>
    public string DigitTokenSecret { get; set; }

    public SecurityKey GetSecurityKey() => SecurityKeyType switch
    {
        SecurityKeyType.Symmetric => GetSymmetricSecurityKey(SymmetricPublicKey),
        SecurityKeyType.Rsa => GetRSASecurityKey(RsaPublicKey.ToJson()),
        _ => null
    };

    public string GetSecurityAlgorithm() => SecurityKeyType switch
    {
        SecurityKeyType.Symmetric => SecurityAlgorithms.HmacSha256Signature,
        SecurityKeyType.Rsa => SecurityAlgorithms.RsaSha256Signature,
        _ => null
    };

    /// <summary>
    /// Gets the server-side secret for digit (OTP) tokens. See <see cref="DigitTokenSecret"/>.
    /// </summary>
    /// <returns>Secret bytes.</returns>
    /// <exception cref="MilvaDeveloperException">If no secret is configured and none can be derived.</exception>
    public byte[] GetDigitTokenSecret()
    {
        if (!string.IsNullOrEmpty(DigitTokenSecret))
            return Encoding.UTF8.GetBytes(DigitTokenSecret);

        if (SecurityKeyType == SecurityKeyType.Symmetric && !string.IsNullOrEmpty(SymmetricPublicKey))
            return HMACSHA256.HashData(Encoding.UTF8.GetBytes(SymmetricPublicKey), Encoding.UTF8.GetBytes(_digitTokenSecretDerivationLabel));

        throw new MilvaDeveloperException("Please configure Token.DigitTokenSecret to generate or validate digit tokens.");
    }

    internal static JsonWebKey GetRSASecurityKey(string json) => new(json);
    internal static SymmetricSecurityKey GetSymmetricSecurityKey(string key) => new(Encoding.UTF8.GetBytes(key));
}
#pragma warning restore CS1591 // Missing XML comment for publicly visible type or member
